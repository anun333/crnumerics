/* gen-tables.c: crfix-tables.h, the constants crfix.c computes with, each correctly rounded by MPFR (2026-10-13).
   make crfix-tables writes it; make check checks that the file is what this prints.

     CRFIX_T2[j]    (2^(j/64) - 1) 2^64, j = 0 .. 63                         2^f's table
     CRFIX_C[k]     (ln 2)^k / k! 2^64, k = 1 .. 7                          2^t - 1's Taylor coefficients
     CRFIX_LOG2E    log2(e) 2^126, as two 64-bit words                       exp's argument reduction
     CRFIX_LN2      ln(2) 2^128, two words
     CRFIX_R16[j]   round(2^16 / (1 + (j + 1/2) / 64)), j = 0 .. 63            log's reduction: 1 + t times this
     CRFIX_L2R[j]   -log2(R16[j] / 2^16) 2^64                                 and the logarithms it takes away
     CRFIX_LNR[j]   -ln(R16[j] / 2^16) 2^64
     CRFIX_INV[k]   2^63 / k, k = 2 .. 9                                     ln(1 + s)'s series
     CRFIX_IL2M1    (1 / ln 2 - 1) 2^63                                       ln to log2
     CRFIX_RS2PI[d] 1 / sqrt(2 pi) 2^64, rounded down (d = 0) and up (d = 1)  GELU's series and tail (2026-10-14)
     CRFIX_MP_LN2[d], CRFIX_MP_LOG2E[d], CRFIX_MP_RS2PI[d]   ln 2, log2(e) and 1 / sqrt(2 pi) 2^256 in five 64-bit
                    words, the lowest first, rounded down (d = 0) and up (d = 1): crfix-mp.c's interval constants
   Every other entry rounded to nearest. */
#include <stdio.h>
#include <stdint.h>
#include <mpfr.h>

static mpfr_t x, y;

/* y (>= 0, < 2^(bits)) scaled by 2^s, to the nearest integer, as one or two 64-bit words */
static void words(mpfr_srcptr v, int s, int two, uint64_t *hi, uint64_t *lo)
{
  mpfr_t t;
  mpfr_init2(t, 512);
  mpfr_mul_2si(t, v, s, MPFR_RNDN);
  mpfr_rint(t, t, MPFR_RNDN);
  mpz_t z;
  mpz_init(z);
  mpfr_get_z(z, t, MPFR_RNDN);
  mpz_t w;
  mpz_init(w);
  mpz_fdiv_r_2exp(w, z, 64);
  *lo = mpz_get_ui(w);
  mpz_fdiv_q_2exp(w, z, 64);
  *hi = mpz_get_ui(w);
  if (!two && *hi) { fprintf(stderr, "gen-tables: a one-word entry needs two\n"); *hi = 0; }
  mpz_clear(w); mpz_clear(z); mpfr_clear(t);
}

int main(void)
{
  mpfr_inits2(512, x, y, (mpfr_ptr)0);
  uint64_t hi, lo;
  printf("/* crfix-tables.h: generated by fix/gen-tables.c (make crfix-tables); do not edit. */\n");
  printf("static const uint64_t CRFIX_T2[64] = {\n");
  for (int j = 0; j < 64; j++) {
    mpfr_set_si(x, j, MPFR_RNDN); mpfr_div_ui(x, x, 64, MPFR_RNDN); mpfr_exp2(y, x, MPFR_RNDN); mpfr_sub_ui(y, y, 1, MPFR_RNDN);
    words(y, 64, 0, &hi, &lo);
    printf("  0x%016llxULL,%s", (unsigned long long)lo, j % 3 == 2 ? "\n" : "");
  }
  printf("\n};\nstatic const uint64_t CRFIX_C[8] = {0,\n");
  mpfr_const_log2(x, MPFR_RNDN);
  mpfr_set_ui(y, 1, MPFR_RNDN);
  for (int k = 1; k <= 7; k++) {
    mpfr_mul(y, y, x, MPFR_RNDN); mpfr_div_ui(y, y, (unsigned long)k, MPFR_RNDN);
    words(y, 64, 0, &hi, &lo);
    printf("  0x%016llxULL,%s", (unsigned long long)lo, k % 3 == 0 ? "\n" : "");
  }
  printf("\n};\n");
  mpfr_set_ui(x, 1, MPFR_RNDN); mpfr_exp(x, x, MPFR_RNDN); mpfr_log2(y, x, MPFR_RNDN);
  words(y, 126, 1, &hi, &lo);
  printf("static const uint64_t CRFIX_LOG2E[2] = {0x%016llxULL, 0x%016llxULL};   /* hi, lo */\n", (unsigned long long)hi, (unsigned long long)lo);
  mpfr_const_log2(y, MPFR_RNDN);
  words(y, 128, 1, &hi, &lo);
  printf("static const uint64_t CRFIX_LN2[2] = {0x%016llxULL, 0x%016llxULL};\n", (unsigned long long)hi, (unsigned long long)lo);
  unsigned r16[64];
  printf("static const uint32_t CRFIX_R16[64] = {\n");
  for (int j = 0; j < 64; j++) {
    mpfr_set_ui(x, 2 * j + 1, MPFR_RNDN); mpfr_div_ui(x, x, 128, MPFR_RNDN); mpfr_add_ui(x, x, 1, MPFR_RNDN);
    mpfr_ui_div(y, 65536, x, MPFR_RNDN);
    words(y, 0, 0, &hi, &lo);
    r16[j] = (unsigned)lo;
    printf("  %u,%s", r16[j], j % 8 == 7 ? "\n" : "");
  }
  printf("};\nstatic const uint64_t CRFIX_L2R[64] = {\n");
  for (int j = 0; j < 64; j++) {
    mpfr_set_ui(x, r16[j], MPFR_RNDN); mpfr_div_2ui(x, x, 16, MPFR_RNDN); mpfr_log2(y, x, MPFR_RNDN); mpfr_neg(y, y, MPFR_RNDN);
    words(y, 64, 0, &hi, &lo);
    printf("  0x%016llxULL,%s", (unsigned long long)lo, j % 3 == 2 ? "\n" : "");
  }
  printf("\n};\nstatic const uint64_t CRFIX_LNR[64] = {\n");
  for (int j = 0; j < 64; j++) {
    mpfr_set_ui(x, r16[j], MPFR_RNDN); mpfr_div_2ui(x, x, 16, MPFR_RNDN); mpfr_log(y, x, MPFR_RNDN); mpfr_neg(y, y, MPFR_RNDN);
    words(y, 64, 0, &hi, &lo);
    printf("  0x%016llxULL,%s", (unsigned long long)lo, j % 3 == 2 ? "\n" : "");
  }
  printf("\n};\nstatic const int64_t CRFIX_INV[10] = {0, 0,\n");
  for (int k = 2; k <= 9; k++) {
    mpfr_set_ui(y, 1, MPFR_RNDN); mpfr_div_ui(y, y, (unsigned long)k, MPFR_RNDN);
    words(y, 63, 0, &hi, &lo);
    printf("  %lldLL,%s", (long long)lo, k % 4 == 1 ? "\n" : "");
  }
  printf("\n};\n");
  mpfr_const_log2(x, MPFR_RNDN); mpfr_ui_div(y, 1, x, MPFR_RNDN); mpfr_sub_ui(y, y, 1, MPFR_RNDN);
  words(y, 63, 0, &hi, &lo);
  printf("static const int64_t CRFIX_IL2M1 = %lldLL;\n", (long long)lo);
  {   /* 1 / sqrt(2 pi) */
    mpfr_t z;
    mpfr_init2(z, 1024);
    mpfr_const_pi(z, MPFR_RNDN); mpfr_mul_2ui(z, z, 1, MPFR_RNDN); mpfr_rec_sqrt(z, z, MPFR_RNDN);
    mpfr_mul_2ui(z, z, 64, MPFR_RNDN);
    mpfr_t f, c;
    mpfr_inits2(1024, f, c, (mpfr_ptr)0);
    mpfr_floor(f, z); mpfr_ceil(c, z);
    printf("static const uint64_t CRFIX_RS2PI[2] = {0x%016llxULL, 0x%016llxULL};\n",
           (unsigned long long)mpfr_get_uj(f, MPFR_RNDN), (unsigned long long)mpfr_get_uj(c, MPFR_RNDN));
    mpfr_clears(z, f, c, (mpfr_ptr)0);
  }
  for (int c = 0; c < 3; c++) {
    printf("static const uint64_t CRFIX_MP_%s[2][5] = {", c == 2 ? "RS2PI" : c ? "LOG2E" : "LN2");
    for (int d = 0; d < 2; d++) {
      mpfr_t z;
      mpfr_init2(z, 1024);
      if (c == 2) { mpfr_const_pi(z, MPFR_RNDN); mpfr_mul_2ui(z, z, 1, MPFR_RNDN); mpfr_rec_sqrt(z, z, MPFR_RNDN); }
      else if (c) { mpfr_set_ui(z, 1, MPFR_RNDN); mpfr_exp(z, z, MPFR_RNDN); mpfr_log2(z, z, MPFR_RNDN); }
      else mpfr_const_log2(z, MPFR_RNDN);
      mpfr_mul_2ui(z, z, 256, MPFR_RNDN);
      if (d) mpfr_ceil(z, z); else mpfr_floor(z, z);
      mpz_t q, r;
      mpz_inits(q, r, (mpz_ptr)0);
      mpfr_get_z(q, z, MPFR_RNDN);
      printf("%s{", d ? ", " : "");
      for (int k = 0; k < 5; k++) {
        mpz_fdiv_r_2exp(r, q, 64);
        printf("%s0x%016llxULL", k ? ", " : "", (unsigned long long)mpz_get_ui(r));
        mpz_fdiv_q_2exp(q, q, 64);
      }
      printf("}");
      mpz_clears(q, r, (mpz_ptr)0);
      mpfr_clear(z);
    }
    printf("};\n");
  }
  mpfr_clears(x, y, (mpfr_ptr)0);
  return 0;
}
