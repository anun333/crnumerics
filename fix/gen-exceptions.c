/* gen-exceptions.c: crfix-exceptions.h (2026-10-14; make crfix-exceptions). For exp, exp2, log, log2, sigmoid and
   tanh, every 16-bit input x (-32768 .. 32767) and every fin (0 .. 31): crfix.c's enclosure of the exact value,
   checked with MPFR to hold it (the bound, on every input: a failure stops the run); then every fout (0 .. 31) and
   mode whose rounding the enclosure leaves undecided, with the specification's result (crfix-ref.c). Saturation
   comes after, so the container is not part of the key. Prints the header to stdout and a summary to stderr. */
#include <stdio.h>
#include <stdlib.h>
#include <stdint.h>
#include "crfix.h"
#include "crfix-internal.h"
#include "crfix-ref.h"

typedef struct { uint32_t key; int64_t val; } entry;
static int cmp(const void *a, const void *b)
{
  uint32_t x = ((const entry *)a)->key, y = ((const entry *)b)->key;
  return x < y ? -1 : x > y;
}

int main(void)
{
  static const char *name[] = {"exp", "exp2", "log", "log2", "sigmoid", "tanh"};
  entry *all = NULL;
  long n = 0, cap = 0, bad = 0, enclosures = 0, per[6] = {0};
  for (int fn = 0; fn < 6; fn++) {
#pragma omp parallel
    {
      entry *mine = NULL;
      long mn = 0, mc = 0, mbad = 0, menc = 0;
#pragma omp for schedule(dynamic, 64)
      for (int x = -32768; x <= 32767; x++)
        for (int fin = 0; fin < 32; fin++) {
          crfix_iv e;
          crfix_enclose_internal(fn, x, fin, &e);
          if (e.kind != CRFIX_IV_EXACT && e.kind != CRFIX_IV_OPEN) continue;
          menc++;
          if (!crfix_ref_inside(fn, x, fin, e.lo.hi, e.lo.lo, e.hi.hi, e.hi.lo, e.kind == CRFIX_IV_EXACT)) {
            if (mbad++ < 5) fprintf(stderr, "BOUND FAILED: %s x %d fin %d\n", name[fn], x, fin);
            continue;
          }
          int64_t ref[128];
          int have = 0;
          for (int i = 0; i < 128; i++) {
            int64_t q;
            if (crfix_round_internal(&e, i / 4, i % 4, &q)) continue;
            if (!have) { crfix_ref1(fn, x, fin, ref); have = 1; }
            if (mn == mc) { mc = mc ? 2 * mc : 256; mine = realloc(mine, mc * sizeof *mine); }
            mine[mn].key = (uint32_t)fn << 28 | (uint32_t)(i % 4) << 26 | (uint32_t)(i / 4) << 21 | (uint32_t)fin << 16 |
                           (uint32_t)(x + 32768);
            mine[mn++].val = ref[i];
          }
        }
#pragma omp critical
      {
        if (n + mn > cap) { cap = (n + mn) * 2 + 256; all = realloc(all, cap * sizeof *all); }
        for (long i = 0; i < mn; i++) all[n++] = mine[i];
        bad += mbad;
        enclosures += menc;
        per[fn] += mn;
      }
      free(mine);
    }
    fprintf(stderr, "%s: %ld undecided\n", name[fn], per[fn]);
  }
  if (bad) { fprintf(stderr, "gen-exceptions: %ld enclosures miss the exact value; no header written\n", bad); return 1; }
  qsort(all, (size_t)n, sizeof *all, cmp);
  printf("/* crfix-exceptions.h: generated by fix/gen-exceptions.c (make crfix-exceptions); do not edit. %ld entries:\n"
         "   the 16-bit inputs, formats and modes whose rounding crfix.c's enclosure leaves undecided, with the\n"
         "   specification's result before saturation. Key: fn << 28 | mode << 26 | fout << 21 | fin << 16 |\n"
         "   (x + 32768). */\n#define CRFIX_NEXC %ld\nstatic const uint32_t crfix_exc_key[%ld] = {\n", n, n, n ? n : 1);
  for (long i = 0; i < n; i++) printf("0x%08xu,%s", all[i].key, i % 8 == 7 ? "\n" : " ");
  if (!n) printf("0");
  printf("};\nstatic const int64_t crfix_exc_val[%ld] = {\n", n ? n : 1);
  for (long i = 0; i < n; i++) printf("%lldLL,%s", (long long)all[i].val, i % 6 == 5 ? "\n" : " ");
  if (!n) printf("0");
  printf("};\n");
  fprintf(stderr, "gen-exceptions: %ld enclosures, every one holding the exact value; %ld undecided cases\n", enclosures, n);
  free(all);
  return 0;
}
